function jsonResponse(obj, status = 200) {
    return new Response(JSON.stringify(obj), { status, headers: corsHeaders });
}

function assemblePrompt(d) {
    // 필수 검증
    const required = ['industry', 'keywords', 'version', 'charCount', 'subheadCount', 'tone'];
    for (const k of required) {
        if (!d[k] || String(d[k]).trim() === '') {
            throw new Error(`필수 항목이 비어있습니다: ${k}`);
        }
    }

    const parts = [];

    // 1. 역할 설정 (간결)
    parts.push(`당신은 다양한 업종의 블로그 글을 전문적으로 작성하는 전문가입니다.
- 업종별 특성과 전문 용어 반영
- 정확한 팩트와 신뢰성 중심`);

    // 2. 버전 규칙 (선택한 것만)
    parts.push(d.version === '모바일' ? MOBILE_RULES : PC_RULES);

    // 3. 톤앤매너 (선택한 것만)
    if (d.tone === '직접입력') {
        parts.push(`📌 적용할 톤앤매너: 사용자 평소 글 스타일 그대로 재현

${USER_STYLE_RULES}

[사용자 평소 글 스타일 예시 - 이 말투를 그대로 따라하세요]
"""
${d.toneSample || '(예시 미입력)'}
"""`);
    } else {
        const detail = TONE_DETAILS[d.tone];
        parts.push(`📌 적용할 톤앤매너: ${d.tone}

${detail}

이 톤을 서론·본론·결론·해시태그까지 글 전체에서 일관성 있게 유지하세요.`);
    }

    // 4. 공통 작성 규칙
    parts.push(COMMON_RULES);

    // 5. 사용자 입력 정보
    parts.push(`━━━━━━━━━━━━━━━━━━━━
📋 사용자 입력 정보
━━━━━━━━━━━━━━━━━━━━

✅ 주제/업종: ${d.industry}
✅ 핵심 키워드/내용 방향: ${d.keywords}
${d.title ? `✅ 선택한 제목: ${d.title}` : '✅ 제목: AI가 5~8개 추천 → 사용자 선택 후 작성'}
✅ 버전: ${d.version === '모바일' ? '모바일 (40자 줄바꿈)' : 'PC (긴 문단)'}
✅ 목표 글자수: ${d.charCount}자 (오차 ±10%)
✅ 소제목 개수: ${d.subheadCount}개`);

    // 6. 작성 시작 명령
    if (d.title) {
        parts.push(`▶️ 위 정보로 즉시 블로그 글을 작성하세요.
"준비되었습니다", "시작할까요?" 같은 멘트 없이 바로 제목부터 서론, 본론, 결론, 해시태그까지 완성된 글을 출력하세요.`);
    } else {
        parts.push(`▶️ 먼저 위 업종과 키워드를 반영한 매력적인 블로그 제목 5~8개를 추천하세요.
사용자가 번호를 선택하면 어떠한 확인 멘트 없이 즉시 블로그 글 작성을 시작하세요.`);
    }

    // 7. 수정 안내
    parts.push(REVISION_GUIDE);

    return parts.join('\n\n');
}

export async function onRequestOptions() {
    return new Response('', { status: 200, headers: corsHeaders });
}

export async function onRequestPost({ request }) {
    try {
        const data = await request.json();
        const prompt = assemblePrompt(data);
        return jsonResponse({ prompt, length: prompt.length });
    } catch (e) {
        return jsonResponse({ error: e.message || '서버 오류' }, 400);
    }
}
