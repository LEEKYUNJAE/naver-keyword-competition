const TONE_DESCRIPTIONS = {
    '전문가형': '전문가형 (격식체) - ~합니다, ~입니다, 전문적이고 신뢰감 있는 어조',
    '친근형': '친근형 - ~해요, ~네요, ~거든요, 편안하고 다가가기 쉬운 어조',
    '정보전달형': '정보전달형 (간결체) - 짧고 명확한 문장, 사실 중심',
    '스토리텔링형': '스토리텔링형 - 경험담, 감정 표현, 독자와의 공감대 형성',
    '교육형': '교육형 - 단계별 설명, ~하는 방법, 쉬운 예시 활용',
    '직접입력': '직접 입력 (사용자 제공 예시 글의 말투를 그대로 재현)',
};

function jsonResponse(obj, status = 200) {
    return new Response(JSON.stringify(obj), { status, headers: corsHeaders });
}

function assemblePrompt(d) {
    // 필수 검증
    const required = ['industry', 'keywords', 'version', 'charCount', 'subheadCount', 'tone'];
    for (const k of required) {
        if (!d[k] || String(d[k]).trim() === '') {
            throw new Error(`필수 항목이 비어있습니다: ${k}`);
        }
    }

    const toneLabel = TONE_DESCRIPTIONS[d.tone] || d.tone;
    const versionLabel = d.version === '모바일' ? '모바일 버전 (짧은 문단, 가독성 최적화)' : 'PC 버전 (긴 문단, 연속적인 흐름)';

    let userInfo = `━━━━━━━━━━━━━━━━━━━━
📋 사용자 입력 정보 (1~7단계 인터랙티브 Q&A 생략, 8단계로 즉시 진행)
━━━━━━━━━━━━━━━━━━━━

✅ 주제/업종: ${d.industry}
✅ 핵심 키워드/내용 방향: ${d.keywords}
${d.title ? `✅ 선택한 제목: ${d.title}` : '✅ 선택한 제목: (AI가 5~8개 제목을 먼저 추천하면, 사용자가 번호를 선택한 뒤 작성)'}
✅ 버전: ${versionLabel}
✅ 목표 글자수: ${d.charCount}자 (오차 ±10%)
✅ 소제목 개수: ${d.subheadCount}개
✅ 톤앤매너: ${toneLabel}`;

    if (d.tone === '직접입력' && d.toneSample) {
        userInfo += `

📝 사용자 평소 글 스타일 예시 (이 말투를 그대로 재현):
"""
${d.toneSample}
"""`;
    }

    userInfo += `

━━━━━━━━━━━━━━━━━━━━`;

    let action;
    if (d.title) {
        action = `위 정보로 즉시 블로그 글 작성을 시작하세요.
"준비되었습니다", "시작할까요?" 같은 멘트 없이 바로 제목부터 시작해서 서론, 본론, 결론, 해시태그까지 완성된 블로그 글을 출력하세요.`;
    } else {
        action = `먼저 위 업종과 키워드를 반영한 블로그 제목 5~8개를 추천해주세요.
사용자가 번호를 선택하면, 어떠한 확인 멘트 없이 즉시 블로그 글 작성을 시작하세요.
바로 제목부터 시작해서 서론, 본론, 결론, 해시태그까지 완성된 블로그 글을 출력하세요.`;
    }

    return `${SYSTEM_INSTRUCTIONS}

${userInfo}

${action}`;
}

export async function onRequestOptions() {
    return new Response('', { status: 200, headers: corsHeaders });
}

export async function onRequestPost({ request }) {
    try {
        const data = await request.json();
        const prompt = assemblePrompt(data);
        return jsonResponse({ prompt, length: prompt.length });
    } catch (e) {
        return jsonResponse({ error: e.message || '서버 오류' }, 400);
    }
}
